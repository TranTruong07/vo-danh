import { rescanCharacter } from './support/rescan-character.mjs';
import { chromium, expect } from '@playwright/test';
import { MongoClient, ObjectId } from 'mongodb';
import { randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';

process.loadEnvFile('.env.local');
const base = process.env.GAME_TEST_BASE_URL || 'http://localhost:3001';
const marker = 'question-probe-' + randomUUID();
const ids = [new ObjectId(), new ObjectId()];
const names = ['Ngô Quyền ' + marker.slice(-6), 'Trần Hưng Đạo ' + marker.slice(-6)];
const client = new MongoClient(process.env.MONGODB_URI);
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const admin = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const player = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
for (const page of [admin, player]) {
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && /hydrated|hydration/i.test(message.text())) errors.push(message.text()); });
}
try {
  await client.connect();
  const db = client.db(process.env.MONGODB_DB_NAME || undefined);
  await mkdir('test-results', { recursive: true });
  await db.collection('characters').insertMany(ids.map((_id, index) => ({ _id, name: names[index], openingLine: marker, image: '/images/history-landscape.webp', backgroundImage: '/images/history-landscape.webp', createdAt: new Date(), updatedAt: new Date() })));
  await player.goto(base + '/admin/questions');
  await expect(player).toHaveURL(/\?auth=login$/);
  await admin.goto(base + '/?auth=login');
  const login = admin.getByRole('dialog');
  await login.getByLabel('Email', { exact: true }).fill(process.env.ADMIN_EMAIL);
  await login.getByLabel('Mật khẩu', { exact: true }).fill(process.env.ADMIN_PASSWORD);
  await login.locator('button[type=submit]').click();
  await expect(admin).toHaveURL(base + '/admin', { timeout: 20000 });
  await admin.locator('.admin-sidebar').getByRole('link', { name: 'Câu hỏi', exact: true }).click();
  await expect(admin.getByRole('heading', { name: 'Câu hỏi theo nhân vật' })).toBeVisible();
  await expect(admin.locator('.admin-sidebar').getByRole('link', { name: 'Câu hỏi', exact: true })).toHaveAttribute('aria-current', 'page');
  await expect(admin.locator('.admin-sidebar a[aria-current=page]')).toHaveCount(1);
  await admin.getByRole('link', { name: '+ Tạo câu hỏi', exact: true }).click();
  await expect(admin).toHaveURL(base + '/admin/questions/new');
  await expect(admin.getByRole('heading', { name: 'Tạo câu hỏi', exact: true })).toBeVisible();
  await admin.getByLabel('Tìm nhanh tên nhân vật', { exact: true }).fill('Ngo Quyen');
  await expect(admin.getByText('1 nhân vật khớp tên', { exact: true })).toBeVisible();
  await admin.getByLabel('Nhân vật', { exact: true }).selectOption(ids[0].toHexString());
  await expect(admin.getByLabel('Nhân vật', { exact: true })).toHaveValue(ids[0].toHexString());
  await admin.getByLabel('Nội dung câu hỏi', { exact: true }).fill('Chiến thắng Bạch Đằng của Ngô Quyền diễn ra năm nào?');
  for (const [index, value] of ['938', '939', '1288', '981'].entries()) await admin.getByLabel('Đáp án ' + 'ABCD'[index], { exact: true }).fill(value);
  await expect(admin.getByLabel('Nhân vật', { exact: true }), 'Character remains selected after filling answers').toHaveValue(ids[0].toHexString());
  await admin.getByRole('radio', { name: 'Chọn A là đáp án đúng' }).check();
  await expect(admin.getByLabel('Nhân vật', { exact: true }), 'Character remains selected after choosing correct answer').toHaveValue(ids[0].toHexString());
  await admin.getByLabel('Khi trả lời đúng', { exact: true }).fill('Đúng rồi! Chiến thắng năm 938. ' + marker);
  await admin.getByLabel('Khi trả lời sai', { exact: true }).fill('Chưa đúng. Hãy nhớ mốc năm 938. ' + marker);
  await admin.screenshot({ path: 'test-results/questions-editor-desktop.png', fullPage: true, caret: 'initial' });
  await admin.getByRole('button', { name: 'Lưu câu hỏi' }).click();
  await expect(admin.getByRole('status').filter({ hasText: 'Đã lưu câu hỏi.' })).toBeVisible();
  const question = await db.collection('character_questions').findOne({ characterId: ids[0].toHexString() });
  expect(question.answers).toEqual(['938', '939', '1288', '981']);
  expect(question.correctIndex).toBe(0);
  await expect(admin.locator('.question-card')).toHaveCount(1);
  await admin.getByText('Xem đáp án & phản hồi', { exact: true }).click();
  await expect(admin.locator('.question-card-detail')).toContainText(question.incorrectFeedback);
  await admin.screenshot({ path: 'test-results/questions-list-desktop.png', fullPage: true, caret: 'initial' });
  // A question is selected from the saved bank; neither answer nor feedback is sent before grading.
  let payload = '';
  player.on('response', async response => { if (response.request().method() === 'POST') { const text = await response.text().catch(() => ''); if (text.includes('expiresAt')) payload = text; } });
  await player.goto(base + '/play/' + ids[0]);
  await expect(player.getByRole('radio')).toHaveCount(4, { timeout: 20000 });
  await expect(player.getByRole('heading', { name: question.question })).toBeVisible();
  await expect.poll(() => payload).not.toBe('');
  expect(payload).not.toContain('correctIndex');
  expect(payload).not.toContain(question.incorrectFeedback);
  await player.getByRole('radio').nth(1).check();
  await player.getByRole('button', { name: 'Chốt đáp án →' }).click();
  await expect(player.getByRole('status')).toContainText(question.incorrectFeedback);
  await rescanCharacter(player, base + '/play/' + ids[0]);
  await expect(player.getByRole('radio').first()).toBeEnabled();
  // Change the source after this round starts; its saved feedback snapshot must remain stable.
  await admin.getByRole('link', { name: 'Chỉnh sửa', exact: true }).click();
  await expect(admin.getByLabel('Khi trả lời đúng', { exact: true })).toHaveValue(question.correctFeedback);
  await admin.getByLabel('Khi trả lời đúng', { exact: true }).fill('Phản hồi đã chỉnh sửa. ' + marker);
  await admin.getByRole('button', { name: 'Lưu câu hỏi' }).click();
  await expect(admin.getByRole('status').filter({ hasText: 'Đã lưu câu hỏi.' })).toBeVisible();
  await player.getByRole('radio').first().check();
  await player.getByRole('button', { name: 'Chốt đáp án →' }).click();
  await expect(player.getByRole('status')).toContainText(question.correctFeedback);
  await rescanCharacter(player, base + '/play/' + ids[0]);
  await expect(player.getByRole('radio').first()).toBeEnabled();
  await player.getByRole('radio').first().check();
  await player.getByRole('button', { name: 'Chốt đáp án →' }).click();
  await expect(player.getByRole('status')).toContainText('Phản hồi đã chỉnh sửa.');
  // Fixtures in the other character verify filtering and page boundaries.
  await db.collection('character_questions').insertMany(Array.from({ length: 11 }, (_, index) => ({ characterId: ids[1].toHexString(), question: `Câu hỏi phân trang ${index + 1} về ${names[1]}?`, answers: ['A', 'B', 'C', 'D'], correctIndex: 1, correctFeedback: marker, incorrectFeedback: marker, createdAt: new Date(), updatedAt: new Date() })));
  await admin.goto(base + '/admin/questions?characterId=' + ids[1]);
  await expect(admin.locator('.question-card')).toHaveCount(10);
  await admin.getByRole('link', { name: 'Trang sau →' }).click();
  await expect(admin.locator('.question-card')).toHaveCount(1);
  await expect(admin).toHaveURL(/page=2/);
  await admin.getByLabel('Tìm theo câu hỏi', { exact: true }).fill('Bạch Đằng');
  await admin.getByLabel('Nhân vật', { exact: true }).selectOption(ids[0].toHexString());
  await admin.getByRole('button', { name: 'Áp dụng bộ lọc' }).click();
  await expect(admin.locator('.question-card')).toHaveCount(1);
  await expect(admin.locator('.question-card')).toContainText(names[0]);
  await admin.setViewportSize({ width: 390, height: 844 });
  expect(await admin.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await admin.screenshot({ path: 'test-results/questions-list-mobile.png', fullPage: true, caret: 'initial' });
  await admin.getByRole('link', { name: 'Chỉnh sửa', exact: true }).click();
  await expect(admin.getByRole('heading', { name: 'Chỉnh sửa câu hỏi', exact: true })).toBeVisible();
  expect(await admin.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await admin.screenshot({ path: 'test-results/questions-editor-mobile.png', fullPage: true, caret: 'initial' });
  await admin.getByRole('button', { name: 'Hủy', exact: true }).click();
  await admin.getByRole('button', { name: 'Xóa', exact: true }).click();
  const confirmation = admin.getByRole('dialog', { name: 'Xóa câu hỏi?' });
  await confirmation.getByRole('button', { name: 'Hủy', exact: true }).click();
  expect(await db.collection('character_questions').countDocuments({ _id: question._id })).toBe(1);
  await admin.getByRole('button', { name: 'Xóa', exact: true }).click();
  await confirmation.getByRole('button', { name: 'Xác nhận xóa' }).click();
  await expect(admin.locator('.question-card')).toHaveCount(0);
  expect(await db.collection('character_questions').countDocuments({ _id: question._id })).toBe(0);
  await expect(admin.getByRole('heading', { name: 'Chưa có câu hỏi' })).toBeVisible();
  expect(errors).toEqual([]);
  console.log('PASS: admin questions tab, create/edit/delete/cancel, accent-insensitive character picker, combined filters, pagination, mobile layout, saved-question gameplay, correct/incorrect feedback snapshots, no answer leaks.');
} catch (error) {
  await admin.screenshot({ path: 'test-results/questions-failure.png', fullPage: true, caret: 'initial' }).catch(() => {});
  console.error('Admin URL:', admin.url());
  throw error;
} finally {
  await browser.close();
  const db = client.db(process.env.MONGODB_DB_NAME || undefined);
  await db.collection('question_cycles').deleteMany({ characterId: { $in: ids.map(String) } });
  await db.collection('quiz_attempts').deleteMany({ characterId: { $in: ids.map(String) } });
  await db.collection('character_questions').deleteMany({ characterId: { $in: ids.map(String) } });
  await db.collection('characters').deleteMany({ _id: { $in: ids }, openingLine: marker });
  await client.close();
}
