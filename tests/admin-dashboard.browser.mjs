import { chromium, expect } from '@playwright/test';
import { MongoClient } from 'mongodb';
import { mkdir } from 'node:fs/promises';

process.loadEnvFile('.env.local');
const base = process.env.GAME_TEST_BASE_URL || 'http://localhost:3001';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
const client = new MongoClient(process.env.MONGODB_URI);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await mkdir('test-results', { recursive: true });
  await page.goto(base);
  await page.locator('header').getByRole('link', { name: 'Quét mã', exact: true }).click();
  await expect(page).toHaveURL(base + '/play');
  await expect(page.getByRole('button', { name: 'Bật camera quét QR' })).toBeVisible();
  await page.goto(base + '/admin');
  await expect(page).toHaveURL(/\?auth=login$/);
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Email', { exact: true }).fill(process.env.ADMIN_EMAIL);
  await dialog.getByLabel('Mật khẩu', { exact: true }).fill(process.env.ADMIN_PASSWORD);
  await dialog.locator('button[type=submit]').click();
  await expect(page).toHaveURL(base + '/admin', { timeout: 20000 });
  await expect(page.getByRole('heading', { name: 'Dashboard quản trị' })).toBeVisible();
  await client.connect();
  const db = client.db(process.env.MONGODB_DB_NAME || undefined);
  const totalCharacters = await db.collection('characters').countDocuments();
  const totalUsers = await db.collection('users').countDocuments({ role: 'user' });
  await expect(page.locator('.metric-card').filter({ hasText: 'Nhân vật lịch sử' }).locator('strong')).toHaveText(new Intl.NumberFormat('vi-VN').format(totalCharacters));
  await expect(page.locator('.metric-card').filter({ hasText: 'Tài khoản người dùng' }).locator('strong')).toHaveText(new Intl.NumberFormat('vi-VN').format(totalUsers));
  await expect(page.locator('.admin-sidebar').getByRole('link', { name: 'Tổng quan' })).toHaveAttribute('aria-current', 'page');
  await expect(page.locator('.admin-sidebar').getByRole('button', { name: 'Đơn hàng Sắp có' })).toBeDisabled();
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true });
  await page.getByRole('link', { name: '7 ngày', exact: true }).click();
  await expect(page).toHaveURL(/days=7$/);
  await expect(page.getByRole('img', { name: /Biểu đồ tài khoản đăng ký 7 ngày/ })).toBeVisible();
  await page.getByRole('tab', { name: /DOANH THU/ }).click();
  await expect(page.getByText('Chưa có dữ liệu bán hàng', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'TÀI KHOẢN MỚI' }).click();
  await page.locator('.admin-sidebar').getByRole('link', { name: 'Nhân vật & QR', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Nhân vật lịch sử' })).toBeVisible();
  await expect(page.locator('.admin-sidebar').getByRole('link', { name: 'Nhân vật & QR', exact: true })).toHaveAttribute('aria-current', 'page');
  await expect(page.getByRole('link', { name: '+ Tạo mới nhân vật', exact: true })).toBeVisible();
  await expect(page.locator('input[name=imageFile]')).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Mở menu quản trị' }).click();
  await expect(page.getByRole('dialog', { name: 'Điều hướng quản trị' })).toBeVisible();
  await page.screenshot({ path: 'test-results/dashboard-menu-mobile.png' });
  await page.getByRole('dialog').getByRole('link', { name: 'Tổng quan' }).click();
  await expect(page).toHaveURL(base + '/admin');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/dashboard-mobile.png', fullPage: true });
  await page.goto(base);
  await expect(page.locator('header').getByRole('link', { name: 'Quét mã', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/header-scan-mobile.png' });
  await page.goto(base + '/admin');
  await page.getByRole('button', { name: 'Mở menu quản trị' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Đăng xuất', exact: true }).click();
  await expect(page).toHaveURL(base + '/');
  expect(errors).toEqual([]);
  console.log('PASS: public header QR entry, admin authorization, actual MongoDB counts, period and chart tabs, sidebar navigation, character form, mobile menu/layout, logout, no browser errors.');
} finally { await browser.close(); await client.close(); }
