import { chromium, expect } from '@playwright/test';
import { MongoClient } from 'mongodb';
import { S3Client, DeleteObjectCommand } from '@aws-sdk/client-s3';
import { randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import sharp from 'sharp';

process.loadEnvFile('.env.local');
const base = process.env.GAME_TEST_BASE_URL || 'http://localhost:3001';
const marker = 'character-ui-' + randomUUID();
const name = 'Nhân vật kiểm thử ' + marker.slice(-8);
const client = new MongoClient(process.env.MONGODB_URI);
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const storage = new S3Client({ region: 'auto', endpoint: `https://${process.env.R2_ACCOUNT_ID}.r2.cloudflarestorage.com`, credentials: { accessKeyId: process.env.R2_ACCESS_KEY_ID, secretAccessKey: process.env.R2_SECRET_ACCESS_KEY } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error' && /hydration|hydrated/i.test(message.text())) errors.push(message.text()); });
const imageKeys = new Set();
try {
  await client.connect();
  const rows = client.db(process.env.MONGODB_DB_NAME || undefined).collection('characters');
  await mkdir('test-results', { recursive: true });
  for (const route of ['/admin/characters/new', '/admin/characters/000000000000000000000000', '/admin/characters/000000000000000000000000/edit']) {
    await page.goto(base + route);
    await expect(page).toHaveURL(/\?auth=login$/);
  }
  const login = page.getByRole('dialog');
  await login.getByLabel('Email', { exact: true }).fill(process.env.ADMIN_EMAIL);
  await login.getByLabel('Mật khẩu', { exact: true }).fill(process.env.ADMIN_PASSWORD);
  await login.locator('button[type=submit]').click();
  await expect(page).toHaveURL(base + '/admin', { timeout: 20000 });
  await page.goto(base + '/admin/characters');
  await expect(page.getByRole('region', { name: 'Danh sách nhân vật' })).toBeVisible();
  await expect(page.locator('input[name=name]')).toHaveCount(0);
  await page.getByRole('link', { name: '+ Tạo mới nhân vật', exact: true }).click();
  await expect(page).toHaveURL(base + '/admin/characters/new');
  await page.getByRole('button', { name: 'Hủy', exact: true }).click();
  await expect(page).toHaveURL(base + '/admin/characters');
  await page.getByRole('link', { name: '+ Tạo mới nhân vật', exact: true }).click();
  await expect(page.locator('input[name=published]')).toHaveCount(0);
  await expect(page.locator('[name=facts]')).toHaveCount(0);
  await page.getByLabel('Tên nhân vật', { exact: true }).fill(name);
  await page.getByLabel('Câu nói mở đầu', { exact: true }).fill('Xin chào! Cùng khám phá lịch sử với tôi. ' + marker);
  const portrait = await sharp({ create: { width: 120, height: 160, channels: 3, background: '#5785cc' } }).png().toBuffer();
  await page.locator('input[name=imageFile]').setInputFiles({ name: 'test.png', mimeType: 'image/png', buffer: portrait });
  const background = await sharp({ create: { width: 600, height: 320, channels: 3, background: '#c4d7ae' } }).png().toBuffer();
  await page.locator('input[name=backgroundImageFile]').setInputFiles({ name: 'background.png', mimeType: 'image/png', buffer: background });
  await expect(page.getByAltText('Xem trước ảnh nền')).toHaveAttribute('src', /^blob:/);
  await expect(page.getByAltText('Xem trước ảnh nhân vật')).toHaveAttribute('src', /^blob:/);
  await page.getByRole('button', { name: 'Lưu nhân vật' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Đã lưu nhân vật.' })).toBeVisible({ timeout: 30000 });
  await expect(page.getByText('Cấu hình câu hỏi AI', { exact: true })).toHaveCount(0);
  const row = await rows.findOne({ openingLine: { $regex: marker } });
  const id = row._id.toHexString();
  expect(row.facts).toBeUndefined();
  expect(row.published).toBeUndefined();
  expect((await page.request.get(base + '/play/' + id)).status()).toBe(200);
  const imageBase = process.env.R2_PUBLIC_BASE_URL.replace(/\/+$/, '') + '/';
  expect(row.image.startsWith(imageBase)).toBe(true);
  imageKeys.add(row.image.slice(imageBase.length));
  imageKeys.add(row.backgroundImage.slice(imageBase.length));
  expect(row.backgroundImage.startsWith(imageBase)).toBe(true);
  expect(row.backgroundImage).not.toBe(row.image);
  expect(row.openingLine).toBe('Xin chào! Cùng khám phá lịch sử với tôi. ' + marker);
  await expect(page).toHaveURL(base + '/admin/characters/' + id + '?saved=1');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(name);
  await expect(page.locator('.character-opening-line')).toHaveText(row.openingLine);
  await expect(page.locator('.character-print canvas')).toBeVisible();
  await expect(page.locator('.character-print .character-qr-opening')).toHaveText(row.openingLine);
  await expect(page.locator('.character-detail .character-background')).toHaveAttribute('src', row.backgroundImage);
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Tải PNG', exact: true }).click();
  expect((await downloadEvent).suggestedFilename()).toBe('nhan-vat-' + id + '.png');
  await page.screenshot({ path: 'test-results/character-detail-desktop.png', fullPage: true, caret: 'initial' });
  await page.getByRole('link', { name: 'Chỉnh sửa', exact: true }).click();
  await expect(page.getByLabel('Tên nhân vật', { exact: true })).toHaveValue(name);
  await page.getByLabel('Tên nhân vật', { exact: true }).fill('Không được lưu');
  await page.getByRole('button', { name: 'Hủy', exact: true }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(name);
  await page.getByRole('link', { name: 'Chỉnh sửa', exact: true }).click();
  await page.getByLabel('Tên nhân vật', { exact: true }).fill(name + ' đã sửa');
  await page.getByLabel('Câu nói mở đầu', { exact: true }).fill('Lời chào đã cập nhật cho người chơi. ' + marker);
  await page.locator('input[name=backgroundImageFile]').setInputFiles({ name: 'background-new.png', mimeType: 'image/png', buffer: background });
  await page.getByRole('button', { name: 'Lưu nhân vật' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Đã lưu nhân vật.' })).toBeVisible();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(name + ' đã sửa');
  const updated = await rows.findOne({ _id: row._id });
  expect(updated.image).toBe(row.image);
  expect(updated.backgroundImage).not.toBe(row.backgroundImage);
  imageKeys.add(updated.backgroundImage.slice(imageBase.length));
  await expect(page.locator('.character-opening-line')).toHaveText(updated.openingLine);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/character-detail-mobile.png', fullPage: true, caret: 'initial' });
  await page.getByRole('link', { name: '← Danh sách nhân vật', exact: true }).click();
  const search = page.locator('.character-search');
  await search.getByRole('searchbox').fill(name);
  await search.getByRole('button', { name: 'Tìm kiếm' }).click();
  await expect(page).toHaveURL(new RegExp('/admin/characters\\?q='));
  await expect(page.locator('.character-table tbody tr')).toHaveCount(1);
  await expect(page.locator('.character-table tbody')).toContainText(name + ' đã sửa');
  await expect(page.locator('.character-table tbody')).toContainText(updated.openingLine);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/character-list-mobile.png', fullPage: true, caret: 'initial' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/character-list-desktop.png', fullPage: true, caret: 'initial' });
  const item = page.locator('.character-table tbody tr');
  await item.getByRole('link', { name: 'Xem chi tiết' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(name + ' đã sửa');
  await page.getByRole('button', { name: 'Xóa', exact: true }).click();
  const confirm = page.getByRole('dialog', { name: 'Xóa nhân vật?' });
  await expect(confirm).toContainText(name + ' đã sửa');
  await confirm.getByRole('button', { name: 'Hủy', exact: true }).click();
  expect(await rows.countDocuments({ _id: row._id })).toBe(1);
  await page.getByRole('link', { name: '← Danh sách nhân vật', exact: true }).click();
  const rowInList = page.locator('.character-table tbody tr').filter({ hasText: name });
  await rowInList.getByRole('button', { name: 'Xóa', exact: true }).click();
  await page.getByRole('dialog', { name: 'Xóa nhân vật?' }).getByRole('button', { name: 'Xác nhận xóa' }).click();
  await expect(rowInList).toHaveCount(0);
  expect(await rows.countDocuments({ _id: row._id })).toBe(0);
  await page.locator('.character-search').getByRole('searchbox').fill(marker);
  await page.locator('.character-search').getByRole('button', { name: 'Tìm kiếm' }).click();
  await expect(page.getByRole('heading', { name: 'Không tìm thấy nhân vật' })).toBeVisible();
  expect((await page.request.get(base + '/admin/characters/' + id)).status()).toBe(404);
  await page.locator('.admin-sidebar').getByRole('button', { name: 'Đăng xuất' }).click();
  await expect(page).toHaveURL(base + '/');
  expect(errors).toEqual([]);
  console.log('PASS: list/create/detail/edit/cancel/delete, server validation, real R2 upload, QR export, search/empty state, mobile layout, admin authorization, no hydration errors.');
} catch (error) {
  await page.screenshot({ path: 'test-results/character-management-failure.png', fullPage: true, caret: 'initial' }).catch(() => {});
  console.error('Form labels:', await page.locator('label').evaluateAll(labels => labels.map(l => ({text:l.textContent, control:l.control?.name})))); console.error('Current page:', page.url(), await page.locator('main').innerText().catch(() => 'unavailable'));
  throw error;
} finally {
  await browser.close();
  const rows = client.db(process.env.MONGODB_DB_NAME || undefined).collection('characters');
  const row = await rows.findOne({ openingLine: { $regex: marker } });
  if (row) {
    const imageBase = process.env.R2_PUBLIC_BASE_URL.replace(/\/+$/, '') + '/';
    for (const image of [row.image, row.backgroundImage]) if (image?.startsWith(imageBase)) imageKeys.add(image.slice(imageBase.length));
  }
  await rows.deleteMany({ openingLine: { $regex: marker } });
  for (const imageKey of imageKeys) if (/^images\/characters\/[a-f0-9-]{36}\.webp$/.test(imageKey)) await storage.send(new DeleteObjectCommand({ Bucket: process.env.R2_BUCKET, Key: imageKey }));
  storage.destroy();
  await client.close();
}
