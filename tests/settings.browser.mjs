import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
process.loadEnvFile('.env.local');
const base = process.env.SETTINGS_TEST_BASE_URL || 'http://localhost:3001';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
try {
  await mkdir('test-results', { recursive: true });
  await page.goto(base + '/admin/settings');
  await expect(page).toHaveURL(/auth=login/);
  const login = page.getByRole('dialog');
  await login.getByLabel('Email', { exact: true }).fill(process.env.ADMIN_EMAIL);
  await login.getByLabel('Mật khẩu', { exact: true }).fill(process.env.ADMIN_PASSWORD);
  await login.locator('button[type=submit]').click();
  await expect(page).toHaveURL(base + '/admin', { timeout: 30000 });
  await page.locator('.admin-sidebar').getByRole('link', { name: 'Thiết lập', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Thiết lập', exact: true })).toBeVisible();
  const currentPrice = await page.getByLabel('Giá bán (VND)').inputValue();
  expect(Number(currentPrice)).toBeGreaterThanOrEqual(1000);
  await page.getByRole('button', { name: 'Lưu thiết lập', exact: true }).click();
  await expect(page.locator('.msg.success')).toContainText('Đã lưu giá bán');
  await page.reload(); await expect(page.getByLabel('Giá bán (VND)')).toHaveValue(currentPrice);
  await page.getByRole('button', { name: 'Kiểm tra kết nối payOS', exact: true }).click();
  await expect(page.locator('.payment-report')).toBeVisible({ timeout: 20000 });
  console.log('payOS diagnostic:', await page.locator('.payment-report').innerText());
  const html = await page.content();
  for (const key of ['PAYOS_CLIENT_ID', 'PAYOS_API_KEY', 'PAYOS_CHECKSUM_KEY']) if (process.env[key]) expect(html.includes(process.env[key])).toBe(false);
  await page.screenshot({ path: 'test-results/settings-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/settings-mobile.png', fullPage: true });
  await page.goto(base + '/shop');
  const formatted = new Intl.NumberFormat('vi-VN', { style: 'currency', currency: 'VND' }).format(Number(currentPrice));
  await expect(page.locator('.product-purchase')).toContainText(formatted);
  await page.goto(base + '/checkout');
  await expect(page.locator('main')).toContainText(formatted);
  expect(errors).toEqual([]);
  console.log('PASS: settings auth, sidebar, save/reload current price, shop and checkout prices, safe payOS diagnostic and mobile layout. No orders or payment links created.');
} finally { await browser.close(); }
